function csv(rows, header) {
  const esc = v => {
    const s = String(v ?? '');
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const body = [header, ...rows].map(r => r.map(esc).join(',')).join('\n');
  return '\uFEFF' + body + '\n';
}

